//! Render the generated source status document.
//!
//! The generated document contract is specified in
//! openspec/changes/oculus-foundation/specs/source-registry/spec.md.

// Rust guideline compliant 2026-10-09

use std::fmt::Write as FmtWrite;

use crate::sources::registry::Registry;
use crate::sources::status::{self, SourceStatus};

const HEADER: &str = "<!-- Generated by src/sources/status_doc.rs. Do not edit by hand. -->";
const INTRO: &str = "# Status";
const NOTE: &str = "This table is generated from the source registry. To change a row, edit the";
const NOTE_2: &str = "manifest in `src/sources/manifests/` and rerun the generator.";
const HEAD: &str = "| Source | Name | Health | Availability | Family | Fetcher |";
const RULE: &str = "| --- | --- | --- | --- | --- | --- |";

/// Render the full status document from a registry.
#[must_use]
pub fn render(registry: &Registry, fixture_root: &std::path::Path) -> String {
    let rows = status::list(registry, fixture_root);
    let mut output = String::new();
    let _ = writeln!(output, "{HEADER}");
    let _ = writeln!(output);
    let _ = writeln!(output, "{INTRO}");
    let _ = writeln!(output);
    let _ = writeln!(output, "{NOTE}");
    let _ = writeln!(output, "{NOTE_2}");
    let _ = writeln!(output);
    let _ = writeln!(output, "{HEAD}");
    let _ = writeln!(output, "{RULE}");
    for row in &rows {
        let line = format_row(row);
        let _ = writeln!(output, "{line}");
    }
    let _ = writeln!(output);
    let _ = writeln!(
        output,
        "The source registry is described in `documentation/013-source-registry.md`.",
    );
    output
}

fn format_row(row: &SourceStatus) -> String {
    format!(
        "| {} | {} | {} | {} | {} | {} |",
        row.id,
        row.name,
        health_label(row.health),
        availability_label(row.availability),
        row.family,
        row.fetcher
    )
}

fn health_label(health: crate::sources::manifest::Health) -> &'static str {
    match health {
        crate::sources::manifest::Health::Working => "working",
        crate::sources::manifest::Health::Keyed => "keyed",
        crate::sources::manifest::Health::Blocked => "blocked",
        crate::sources::manifest::Health::Stale => "stale",
        crate::sources::manifest::Health::RequiresSlug => "requires_slug",
        crate::sources::manifest::Health::BrowserOnly => "browser_only",
    }
}

fn availability_label(availability: status::Availability) -> &'static str {
    match availability {
        status::Availability::Ready => "ready",
        status::Availability::MissingCredentials => "missing_credentials",
        status::Availability::MissingSlug => "missing_slug",
        status::Availability::Blocked => "blocked",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const HEADER_ROWS: usize = 2;

    #[test]
    fn rendered_document_matches_registry_count() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
        let registry = crate::sources::custom::load(
            &root.join("src/sources/manifests"),
            &crate::sources::custom::directory(),
        )
        .expect("registry loads");
        let text = render(&registry, &root.join("tests/fixtures"));
        let data_rows = text.lines().filter(|line| line.starts_with("| ")).count() - HEADER_ROWS;
        assert_eq!(data_rows, registry.len());
    }
}
